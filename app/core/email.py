logger = logging.getLogger("autofix.email")

VERIFY_EMAIL = "VERIFY_EMAIL"
PASSWORD_RESET = "PASSWORD_RESET"


def email_delivery_configured() -> bool:
    """Whether a public link and exactly one TLS-protected SMTP mode are configured."""
    if not settings.SMTP_HOST or not settings.SMTP_FROM_EMAIL:
        return False
    if bool(settings.SMTP_USERNAME) != bool(settings.SMTP_PASSWORD):
        return False
    if settings.SMTP_USE_SSL == settings.SMTP_USE_STARTTLS:
        return False
    app_url = settings.PUBLIC_APP_URL.strip()
    if not app_url.startswith(("https://", "http://")):
        return False
    if settings.is_production and not app_url.startswith("https://"):
        return False
    if settings.is_production and app_url.startswith("http://localhost"):
        return False
    return True


def _verification_payload(email: str, full_name: str, token: str) -> tuple[str, str, str, str]:
    link = f"{settings.PUBLIC_APP_URL.rstrip('/')}/verify-email#token={quote(token, safe='')}"
    safe_name = html.escape(full_name or "there")
    text_body = (
        f"Hello {full_name or 'there'},\n\nVerify your email address within 24 hours:\n{link}\n\n"
        "If you did not create this account, you can ignore this message.\n"
    )
    html_body = (
        f"<p>Hello {safe_name},</p><p>Confirm your email address using the secure link below. "
        f"The link expires in 24 hours.</p><p><a href=\"{html.escape(link, quote=True)}\">Verify email</a></p>"
        "<p>If you did not create this account, you can ignore this message.</p>"
    )
    return email, "Verify your AutoFix account", text_body, html_body


def _password_reset_payload(email: str, full_name: str, token: str) -> tuple[str, str, str, str]:
    link = f"{settings.PUBLIC_APP_URL.rstrip('/')}/reset-password#token={quote(token, safe='')}"
    safe_name = html.escape(full_name or "there")
    text_body = (
        f"Hello {full_name or 'there'},\n\nReset your password within 60 minutes:\n{link}\n\n"
        "If you did not request this change, ignore this message.\n"
    )
    html_body = (
        f"<p>Hello {safe_name},</p><p>Use the secure link below to set a new password. "
        f"The link expires in 60 minutes.</p><p><a href=\"{html.escape(link, quote=True)}\">Reset password</a></p>"
        "<p>If you did not request this change, ignore this message.</p>"
    )
    return email, "Reset your AutoFix password", text_body, html_body


async def _queue_message(session: AsyncSession, user_id, message_type: str) -> None:
    """Persist only the target user and message type, never a live secret link."""
    if message_type not in {VERIFY_EMAIL, PASSWORD_RESET}:
        raise ValueError("Unsupported email message type")
    await session.execute(
        update(EmailOutbox)
        .where(
            EmailOutbox.user_id == user_id,
            EmailOutbox.message_type == message_type,
            EmailOutbox.status == "PENDING",
        )
        .values(status="FAILED", last_error="Superseded")
    )
    session.add(
        EmailOutbox(
            user_id=user_id,
            message_type=message_type,
            status="PENDING",
            attempts=0,
            available_at=datetime.now(UTC),
        )
    )


async def queue_verification_email(session: AsyncSession, user_id) -> None:
    """Queue verification by user ID; the one-time token is generated by the worker."""
    await _queue_message(session, user_id, VERIFY_EMAIL)


async def queue_password_reset_email(session: AsyncSession, user_id) -> None:
    """Queue password recovery by user ID; the one-time token is generated by the worker."""
    await _queue_message(session, user_id, PASSWORD_RESET)


def _send_sync(message: EmailMessage) -> None:
    context = ssl.create_default_context()
    if settings.SMTP_USE_SSL:
        with smtplib.SMTP_SSL(
            settings.SMTP_HOST,
            settings.SMTP_PORT,
            timeout=settings.SMTP_TIMEOUT_SECONDS,
            context=context,
        ) as server:
            if settings.SMTP_USERNAME and settings.SMTP_PASSWORD:
                server.login(settings.SMTP_USERNAME, settings.SMTP_PASSWORD)
            server.send_message(message)
        return

    with smtplib.SMTP(
        settings.SMTP_HOST,
        settings.SMTP_PORT,
        timeout=settings.SMTP_TIMEOUT_SECONDS,
    ) as server:
        server.ehlo()
        server.starttls(context=context)
        server.ehlo()
        if settings.SMTP_USERNAME and settings.SMTP_PASSWORD:
            server.login(settings.SMTP_USERNAME, settings.SMTP_PASSWORD)
        server.send_message(message)


async def _send(to_email: str, subject: str, text_body: str, html_body: str) -> None:
    if not email_delivery_configured():
        raise RuntimeError("SMTP email delivery is not configured")
    message = EmailMessage()
    message["Subject"] = subject
    message["From"] = settings.SMTP_FROM_EMAIL
    message["To"] = to_email
    message.set_content(text_body)
    message.add_alternative(html_body, subtype="html")
    await asyncio.to_thread(_send_sync, message)


async def _prepare_message(user_id, message_type: str) -> dict[str, str] | None:
    """Generate a token just before sending; persist only its digest on the user row."""
    async with AsyncSessionFactory() as session:
        result = await session.execute(
            select(User).where(User.id == user_id).with_for_update()
        )
        user = result.scalar_one_or_none()
        if user is None or not user.is_active:
            return None
        if message_type == VERIFY_EMAIL and user.email_verified:
            return None
        if message_type not in {VERIFY_EMAIL, PASSWORD_RESET}:
            raise ValueError("Unsupported email outbox message type")

        now = datetime.now(UTC)
        full_name = f"{user.first_name} {user.last_name}".strip()
        if message_type == VERIFY_EMAIL:
            token = secrets.token_urlsafe(32)
            user.email_verification_token_hash = hashlib.sha256(token.encode("utf-8")).hexdigest()
            user.email_verification_expires_at = now + timedelta(hours=24)
            recipient, subject, text_body, html_body = _verification_payload(
                user.email, full_name, token
            )
        else:
            token = generate_password_reset_token(user.email, expires_minutes=60)
            user.password_reset_token_hash = hashlib.sha256(token.encode("utf-8")).hexdigest()
            user.password_reset_expires_at = now + timedelta(minutes=60)
            recipient, subject, text_body, html_body = _password_reset_payload(
                user.email, full_name, token
            )

        await session.commit()

    # The raw token exists only in this worker's process memory and the outbound message.
    return {
        "recipient_email": recipient,
        "subject": subject,
        "text_body": text_body,
        "html_body": html_body,
    }


async def _finish_delivery(
    *,
    email_id: str,
    claim_time: datetime,
    succeeded: bool,
    error_name: str | None = None,
) -> None:
    """Update delivery state only if this worker still owns the claim."""
    now = datetime.now(UTC)
    async with AsyncSessionFactory() as session:
        result = await session.execute(
            select(EmailOutbox).where(EmailOutbox.id == email_id).with_for_update()
        )
        row = result.scalar_one_or_none()
        if row is None or row.status != "PROCESSING" or row.locked_at != claim_time:
            return

        row.locked_at = None
        if succeeded:
            row.status = "SENT"
            row.sent_at = now
            row.last_error = error_name
        else:
            row.last_error = error_name or "DeliveryError"
            if row.attempts >= settings.EMAIL_OUTBOX_MAX_ATTEMPTS:
                row.status = "FAILED"
            else:
                row.status = "PENDING"
                backoff_seconds = min(3600, 30 * (2 ** min(row.attempts - 1, 7)))
                row.available_at = now + timedelta(seconds=backoff_seconds)
        await session.commit()


async def _deliver_claimed(item: dict) -> None:
    try:
        payload = await _prepare_message(item["user_id"], item["message_type"])
        if payload is None:
            await _finish_delivery(
                email_id=item["id"],
                claim_time=item["locked_at"],
                succeeded=True,
                error_name="NotRequired",
            )
            return
        await _send(
            payload["recipient_email"],
            payload["subject"],
            payload["text_body"],
            payload["html_body"],
        )
    except asyncio.CancelledError:
        raise
    except Exception as exc:
        logger.error("Queued email delivery failed (%s)", type(exc).__name__)
        await _finish_delivery(
            email_id=item["id"],
            claim_time=item["locked_at"],
            succeeded=False,
            error_name=type(exc).__name__,
        )
    else:
        await _finish_delivery(
            email_id=item["id"],
            claim_time=item["locked_at"],
            succeeded=True,
        )


async def dispatch_email_outbox_batch() -> int:
    """Claim a bounded batch with SKIP LOCKED, then send without holding DB connections."""
    now = datetime.now(UTC)
    stale_lock = now - timedelta(seconds=settings.EMAIL_OUTBOX_LOCK_SECONDS)
    async with AsyncSessionFactory() as session:
        result = await session.execute(
            select(EmailOutbox)
            .where(
                or_(
                    and_(
                        EmailOutbox.status == "PENDING",
                        EmailOutbox.available_at <= now,
                    ),
                    and_(
                        EmailOutbox.status == "PROCESSING",
                        or_(
                            EmailOutbox.locked_at.is_(None),
                            EmailOutbox.locked_at <= stale_lock,
                        ),
                    ),
                )
            )
            .order_by(EmailOutbox.created_at.asc())
            .limit(max(1, settings.EMAIL_OUTBOX_BATCH_SIZE))
            .with_for_update(skip_locked=True)
        )
        rows = list(result.scalars().all())
        if not rows:
            return 0

        claimed: list[dict] = []
        for row in rows:
            row.status = "PROCESSING"
            row.locked_at = now
            row.attempts += 1
            claimed.append(
                {
                    "id": row.id,
                    "locked_at": now,
                    "user_id": row.user_id,
                    "message_type": row.message_type,
                }
            )
        await session.commit()

    await asyncio.gather(*(_deliver_claimed(item) for item in claimed), return_exceptions=True)
    return len(claimed)


async def run_email_outbox_worker(stop_event: asyncio.Event) -> None:
    """Poll the durable outbox; multiple workers safely share rows through SKIP LOCKED."""
    while not stop_event.is_set():
        try:
            processed = await dispatch_email_outbox_batch()
        except asyncio.CancelledError:
            raise
        except Exception as exc:
            logger.error("Email outbox worker cycle failed (%s)", type(exc).__name__)
            processed = 0

        if processed:
            continue
        try:
            await asyncio.wait_for(
                stop_event.wait(),
                timeout=max(0.25, settings.EMAIL_OUTBOX_POLL_SECONDS),
            )
        except TimeoutError:
            pass
